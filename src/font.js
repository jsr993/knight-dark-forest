const CHAR_W = 5;
const CHAR_H = 7;

// Ширина строки в пикселях при заданном масштабе и промежутке между буквами
export function textWidth(text, scale = 1, spacing = 1) {
  if (!text.length) return 0;
  return (text.length * (CHAR_W + spacing) - spacing) * scale;
}

// Нарисовать текст. scale — во сколько раз увеличить букву (1, 2, 3...)
export function drawText(ctx, text, x, y, color = '#ffffff', scale = 1, spacing = 1) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch];
    if (glyph) {
      for (let row = 0; row < CHAR_H; row++) {
        for (let col = 0; col < CHAR_W; col++) {
          if (glyph[row][col] === 'X') {
            ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
          }
        }
      }
    }
    cx += (CHAR_W + spacing) * scale;
  }
}

// Нарисовать текст по центру экрана (по горизонтали)
export function drawTextCentered(ctx, text, screenW, y, color = '#ffffff', scale = 1) {
  const w = textWidth(text, scale);
  drawText(ctx, text, Math.round((screenW - w) / 2), y, color, scale);
}
